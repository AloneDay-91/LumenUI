// Writes src/lib/vue-examples.ts from vue/src/examples/<docs-slug>.vue, so the docs
// show the exact Vue source that vue-tsc checks and the playground renders.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const examplesDir = path.join(root, "vue/src/examples")
const uiDir = path.join(root, "vue/src/components/ui")

// Docs slug -> Vue registry item, when the Vue port uses another name.
const ITEM_FALLBACK = { menu: "dropdown-menu" }

const examples = {}
for (const fileName of readdirSync(examplesDir).sort()) {
  if (!fileName.endsWith(".vue")) {
    continue
  }
  const slug = fileName.replace(/\.vue$/, "")
  const item = existsSync(path.join(uiDir, slug)) ? slug : ITEM_FALLBACK[slug]
  if (!item || !existsSync(path.join(uiDir, item))) {
    throw new Error(`vue/src/examples/${fileName} has no component folder in vue/src/components/ui`)
  }
  examples[slug] = { item, code: readFileSync(path.join(examplesDir, fileName), "utf8").trimEnd() }
}

writeFileSync(
  path.join(root, "src/lib/vue-examples.ts"),
  `// Generated by \`npm run registry\` from vue/src/examples. Do not edit.\n\nexport const VUE_EXAMPLES: Record<string, { item: string; code: string }> = ${JSON.stringify(examples, null, 2)}\n`
)
console.log(`Wrote ${Object.keys(examples).length} Vue examples to src/lib/vue-examples.ts`)
