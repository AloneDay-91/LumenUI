"use client"

import { fade } from "@remotion/transitions/fade"
import { linearTiming, TransitionSeries } from "@remotion/transitions"
import { Fragment, type ComponentType } from "react"
import { Audio } from "@remotion/media"
import { AbsoluteFill, Easing, interpolate, staticFile, useCurrentFrame, useVideoConfig } from "remotion"

import { AgentSteps, DURATION as AGENT_STEPS } from "./agent-steps"
import { BrandWheel, DURATION as BRAND_WHEEL } from "./brand-wheel"
import { CaptureReveal, DURATION as CAPTURE_REVEAL } from "./capture-reveal"
import { CheckCycle, DURATION as CHECK_CYCLE } from "./check-cycle"
import { DURATION as PORTAL_INTRO, PortalIntro } from "./portal-intro"
import { DURATION as PROMPT_SEND, PromptSend } from "./prompt-send"
import { DURATION as ROSTER_GRANT, RosterGrant } from "./roster-grant"
import { DURATION as SKY_LOCKUP, SkyLockup } from "./sky-lockup"
import { StageModeContext, type StageMode } from "./stage"
import { DURATION as WORD_GATHER, WordGather } from "./word-gather"
import { DURATION as WORD_WHEEL, WordWheel } from "./word-wheel"

export const SHOWCASE_FPS = 30
export const SHOWCASE_WIDTH = 1920
export const SHOWCASE_HEIGHT = 1080
/** Every scene hands over to the next on a long, eased crossfade: no hard cuts. */
const CROSSFADE = 20

/**
 * The story of the design system, one snapcn shot per beat: the intro, the
 * components, the AI patterns, the copy-paste flow, the logo lockup.
 */
export const SHOWCASE_SCENES: readonly {
  id: string
  name: string
  durationInFrames: number
  component: ComponentType
}[] = [
  { id: "portal-intro", name: "Intro", durationInFrames: PORTAL_INTRO, component: PortalIntro },
  { id: "word-gather", name: "What it is", durationInFrames: WORD_GATHER, component: WordGather },
  { id: "roster-grant", name: "Components", durationInFrames: ROSTER_GRANT, component: RosterGrant },
  { id: "word-wheel", name: "Frameworks", durationInFrames: WORD_WHEEL, component: WordWheel },
  { id: "prompt-send", name: "AI · Prompt", durationInFrames: PROMPT_SEND, component: PromptSend },
  { id: "agent-steps", name: "AI · Agent", durationInFrames: AGENT_STEPS, component: AgentSteps },
  { id: "brand-wheel", name: "AI · Models", durationInFrames: BRAND_WHEEL, component: BrandWheel },
  { id: "check-cycle", name: "What you build", durationInFrames: CHECK_CYCLE, component: CheckCycle },
  { id: "capture-reveal", name: "Copy-paste", durationInFrames: CAPTURE_REVEAL, component: CaptureReveal },
  { id: "sky-lockup", name: "Lockup", durationInFrames: SKY_LOCKUP, component: SkyLockup },
]

export const SHOWCASE_DURATION =
  SHOWCASE_SCENES.reduce((sum, scene) => sum + scene.durationInFrames, 0) -
  CROSSFADE * (SHOWCASE_SCENES.length - 1)

export type LumenShowcaseProps = {
  mode?: StageMode
  /** Off for the silent loop on the landing page, so the track is never even fetched. */
  music?: boolean
}

export function LumenShowcase({ mode = "light", music = true }: LumenShowcaseProps) {
  const frame = useCurrentFrame()
  const { durationInFrames } = useVideoConfig()
  return (
    <StageModeContext.Provider value={mode}>
    <AbsoluteFill className={`${mode} bg-background`}>
      {/* An original soundtrack, generated by scripts/generate-showcase-music.mjs (`npm run music`). */}
      {music ? (
        <>
          {/* Inline keyframes so Studio can edit the fade in, the level and the fade out.
              The file is mastered to −16 LUFS: 1 is the platform norm (YouTube, socials),
              0.5 (about −22 LUFS) sits quietly under the picture on the site. */}
          <Audio
            name="Soundtrack"
            src={staticFile("video/lumen-theme.mp3")}
            volume={interpolate(frame, [0, 20, durationInFrames - 60, durationInFrames], [0, 0.5, 0.5, 0], {
              extrapolateLeft: "clamp",
              extrapolateRight: "clamp"
            })}
          />
        </>
      ) : null}
      <TransitionSeries>
        {SHOWCASE_SCENES.map(({ id, name, durationInFrames, component: Scene }, i) => (
          <Fragment key={id}>
            {i > 0 ? (
              <TransitionSeries.Transition
                presentation={fade()}
                timing={linearTiming({ durationInFrames: CROSSFADE, easing: Easing.inOut(Easing.cubic) })}
              />
            ) : null}
            <TransitionSeries.Sequence name={name} durationInFrames={durationInFrames}>
              <Scene />
            </TransitionSeries.Sequence>
          </Fragment>
        ))}
      </TransitionSeries>
    </AbsoluteFill>
    </StageModeContext.Provider>
  )
}
